    private void invoicereturnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_invoicereturnActionPerformed
        int i = JOptionPane.showConfirmDialog(this, "Are you sure that you going to return this item?");
        int k = JOptionPane.showConfirmDialog(this, "Invoice return completed?");
        int j = jTable1.getSelectedRow();
        try {
            if (i == 0) {
                DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
                String packno = dtm.getValueAt(j, 0).toString();
                int qty = Integer.parseInt(dtm.getValueAt(j, 3).toString());

                String returnv = dtm.getValueAt(j, 4).toString();
                returnValue += Double.parseDouble(returnv);//anthimata meke value eka 0 krnna
                exchangevalue.setText("" + returnValue);

                ResultSet rs = MyDB.search("select quantity from item where pack_idpack = '" + packno + "' ");
                if (rs.next()) {
                    int Aqty = Integer.parseInt(rs.getString("quantity"));
                    int Add = Aqty + qty;

                    MyDB.iud("update item set quantity = '" + Add + "' where pack_idpack = '" + packno + "' ");//qty 1k update wenawa
                    MyDB.iud("delete from invoiceitemi where item_pack_idpack = '" + packno + "'");//item eka delete wenawa
                    String val = dtm.getValueAt(j, 4).toString();
                    double v = Double.parseDouble(val);
                    double net = Double.parseDouble(netlabel.getText());
                    double amo = net - v;
                    sublabel.setText("" + amo);
                    netlabel.setText("" + amo);
                    dtm.removeRow(j);

                    if (k == 0) {
                        generateInvoiceId();
                        barcodenumber.setText("");
                        invoicedno.setText("");
                        sublabel.setText("");
                        discount.setText("");
                        netlabel.setText("");
                        cashpayment.setText("");
                        cardpayment.setText("");
                        barcodenumber.grabFocus();
                        qtylabel.setText("");
                        dtm.setRowCount(0);
                    }
                }

            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_invoicereturnActionPerformed

