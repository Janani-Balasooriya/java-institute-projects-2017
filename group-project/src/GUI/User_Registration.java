    private void txt6KeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt6KeyTyped
        if (txt6.getText().length() < 9) {
            txt6.setBackground(Color.red);
        } else {
            txt6.setBackground(Color.white);
        }
        if (txt6.getText().length() < 9) {
            if (!Character.isDigit(evt.getKeyChar())) {
                evt.consume();
            }
        } else if (txt6.getText().length() < 10) {
            if (!Character.toString(evt.getKeyChar()).equalsIgnoreCase("V")) {
                evt.consume();
                
            } else {
                evt.setKeyChar(Character.toUpperCase(evt.getKeyChar()));
            }
        } else {
            evt.consume();
        }
    }//GEN-LAST:event_txt6KeyTyped

