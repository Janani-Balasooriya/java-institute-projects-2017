    private void setDateAndTime() {
        Timer t = new Timer(1000, new ActionListener() {

            @Override
            public void actionPerformed(ActionEvent e) {
                d = new Date();
                sdf = new SimpleDateFormat("yyyy-MM-dd");
                datelabel.setText(sdf.format(d));
                sdf = new SimpleDateFormat("HH:mm:ss");
                timelabel.setText(sdf.format(d));
            }
        });
        t.start();
    }

    private void AddtoCart() {
        try {
            barcodeno.grabFocus();
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);
            ResultSet rs = MyDB.search("select idpack,category_name,unitprice,sellingprice,description,quantity from pack where quantity !=0 or quantity !=null ");
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("idpack"));
                v.add(rs.getString("category_name"));
                v.add(rs.getString("quantity"));
                v.add(rs.getString("unitprice"));
                v.add(rs.getString("sellingprice"));
                v.add(rs.getString("description"));
                dtm.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

