    private void txt5KeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt5KeyTyped
        if (txt5.getText().length() < 9) {
            txt5.setBackground(Color.red);
        } else {
            txt5.setBackground(Color.white);
        }
        if (txt5.getText().length() < 9) {
            if (!Character.isDigit(evt.getKeyChar())) {
                evt.consume();
            }
        } else if (txt5.getText().length() < 10) {
            if (!Character.toString(evt.getKeyChar()).equalsIgnoreCase("V")) {
                evt.consume();
                
            } else {
                evt.setKeyChar(Character.toUpperCase(evt.getKeyChar()));
            }
        } else {
            evt.consume();
        }
    }//GEN-LAST:event_txt5KeyTyped

