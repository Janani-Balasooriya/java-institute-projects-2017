    private void txt7KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt7KeyReleased
        try {
            ResultSet rs = MyDB.search("select NIC from supplier where NIC='" + txt7.getText() + "'");
            if (rs.next()) {
                String ch = rs.getString("NIC");
                String s = txt7.getText();
                evt.consume();
                if (ch == s) {
                    JOptionPane.showMessageDialog(this, "");
                    evt.consume();
                } else {
                    JOptionPane.showMessageDialog(this, " INVALIED ALLREADY ENTERED!");
                    char c = evt.getKeyChar();
                    evt.consume();
                    txt7.setText("");
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }


    }//GEN-LAST:event_txt7KeyReleased

