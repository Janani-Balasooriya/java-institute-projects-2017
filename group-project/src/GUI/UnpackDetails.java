    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {

            int i = jTable1.getSelectedRow();
            String id = jTable1.getValueAt(i, 0).toString();
            int qt = Integer.parseInt(jTable1.getValueAt(i, 3).toString());
            int aqt = Integer.parseInt(jTable1.getValueAt(i, 4).toString());
            double price = Double.parseDouble(jTable1.getValueAt(i, 5).toString());

            ResultSet rs = MyDB.search("select category_name from pack inner join unpack on pack.idpack = unpack.pack_idpack where"
                    + " pack_idpack = '" + id + "' ");
            if (rs.next()) {
           String pname = rs.getString("category_name");
            UnpackToTransfer.unpackDetailsToTransfer(id, qt, aqt, price, pname);
            }
            UnpackToTransfer.availableqty.grabFocus();
            UnpackToTransfer.reasonprice.setEnabled(false);
            this.dispose();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Please select pack to continue");
//            e.printStackTrace();
        }

    }//GEN-LAST:event_jButton2ActionPerformed

