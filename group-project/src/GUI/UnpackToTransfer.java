    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            ResultSet rs1 = MyDB.search("select newbarcode from transfer where newbarcode = '" + newbarcode.getText() + "'");
            if (rs1.next()) {
                JOptionPane.showMessageDialog(this, "This item is Allready in the items");
                ClearAll();
                GeneratePackToItemId();
            } else {
                if (sellprice.getText() != null & sellprice.getText().trim().length() != 0) {

                    MyDB.iud("insert into transfer (newbarcode,quantity,availableqty,date,time,unpack_pack_idpack,sellingprice,user_iduser,category_name)"
                            + " values ('" + newbarcode.getText() + "','" + qty.getText() + "','" + availableqty.getText() + "',"
                            + "'" + datelabel.getText() + "','" + timelabel.getText() + "','" + barcodeno.getText() + "',"
                            + "'" + sellprice.getText() + "','"+Login.getUserIdRecord()+"','" + packname.getText() + "')");

                    if (reasonprice.equals(true)) {
                        MyDB.iud("insert into priceretail (price,reason,date,time,transfer_newbarcode) values ('" + sellprice.getText() + "',"
                                + "'" + reasonprice.getText() + "','" + datelabel.getText() + "','" + timelabel.getText() + "',"
                                + "'" + newbarcode.getText() + "')");
                    } else {
                        MyDB.iud("insert into priceretail (price,date,time,transfer_newbarcode) values ('" + sellprice.getText() + "',"
                                + "'" + datelabel.getText() + "','" + timelabel.getText() + "',"
                                + "'" + newbarcode.getText() + "')");
                    }

                    ResultSet rs = MyDB.search("select availableqty from unpack where pack_idpack = '" + barcodeno.getText() + "'");

                    if (rs.next()) {
                        int nowqty = Integer.parseInt(rs.getString("availableqty"));
                        int afqty = Integer.parseInt(availableqty.getText());
                        int balqty = nowqty - afqty;

                        MyDB.iud("update unpack set availableqty = '" + balqty + "' where pack_idpack = '" + barcodeno.getText() + "'");
                        JOptionPane.showMessageDialog(this, "Successfully Added to Transfer");
                        AddtoCart();
                        ClearAll();
                        GeneratePackToItemId();
                    } else {
                        System.out.println("Not Updated Qty");
                    }

                } else {
                    JOptionPane.showMessageDialog(this, "Please give a price to unpack");
                }
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

