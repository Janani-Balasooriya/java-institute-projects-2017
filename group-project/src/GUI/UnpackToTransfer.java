    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        try {
            int i = jTable1.getSelectedRow();
            if (jTable1.getValueAt(i, 0) != null && jTable1.getValueAt(i, 0).toString().trim().length() != 0) {
                newbarcode.setText(jTable1.getValueAt(i, 0).toString());
                String id = jTable1.getValueAt(i, 0).toString();
                ResultSet rs = MyDB.search("select unitprice from unpack inner join transfer on unpack.pack_idpack = transfer.unpack_pack_idpack where "
                        + "newbarcode = '" + id + "'");
                if (rs.next()) {
                    unitprice.setText(rs.getString("unitprice"));
                }
            } else {
                newbarcode.setText("");
            }

            if (jTable1.getValueAt(i, 1) != null && jTable1.getValueAt(i, 1).toString().trim().length() != 0) {
                packname.setText(jTable1.getValueAt(i, 1).toString());
            } else {
                packname.setText("");
            }

            if (jTable1.getValueAt(i, 2) != null && jTable1.getValueAt(i, 2).toString().trim().length() != 0) {
                qty.setText(jTable1.getValueAt(i, 2).toString());
            } else {
                qty.setText("");
            }

            if (jTable1.getValueAt(i, 3) != null && jTable1.getValueAt(i, 3).toString().trim().length() != 0) {
                availableqty.setText(jTable1.getValueAt(i, 3).toString());
            } else {
                availableqty.setText("");
            }

            if (jTable1.getValueAt(i, 6) != null && jTable1.getValueAt(i, 6).toString().trim().length() != 0) {
                sellprice.setText(jTable1.getValueAt(i, 6).toString());
            } else {
                sellprice.setText("");
            }

            if (jTable1.getValueAt(i, 7) != null && jTable1.getValueAt(i, 7).toString().trim().length() != 0) {
                barcodeno.setText(jTable1.getValueAt(i, 7).toString());
            } else {
                barcodeno.setText("");
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jTable1MouseClicked

    private void barcodenoKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_barcodenoKeyReleased
        try {
            ResultSet rs = MyDB.search("select newbarcode,quantity,transfer.availableqty,unpack_pack_idpack,sellingprice,category_name,unitprice from "
                    + "transfer inner join unpack on transfer.unpack_pack_idpack = unpack.pack_idpack where "
                    + "unpack_pack_idpack = '" + barcodeno.getText() + "'");
            if (rs.next()) {
                newbarcode.setText(rs.getString("newbarcode"));
                packname.setText(rs.getString("category_name"));
                qty.setText(rs.getString("quantity"));
                availableqty.setText(rs.getString("availableqty"));
                unitprice.setText(rs.getString("unitprice"));
                sellprice.setText(rs.getString("sellingprice"));
                reasonprice.setEnabled(true);
                barcodeno.grabFocus();

            } else {
                barcodeno.grabFocus();
                newbarcode.setText("");
                packname.setText("");
                qty.setText("");
                availableqty.setText("");
                unitprice.setText("");
                sellprice.setText("");
                reasonprice.setEnabled(false);
                GeneratePackToItemId();
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_barcodenoKeyReleased

