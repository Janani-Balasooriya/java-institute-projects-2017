    private void GeneratePackToItemId() {
        try {
            ResultSet rs = MyDB.search("select max(newbarcode) from transfer");
            if (rs.first()) {
                newbarcode.setText(rs.getInt(1) + 1 + "");
            } else if (!rs.first()) {
                System.out.println("False");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

