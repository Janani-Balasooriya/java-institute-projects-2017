    private void setDateAndTime() {
        Timer t = new Timer(1000, new ActionListener() {

            @Override
            public void actionPerformed(ActionEvent e) {
                d = new Date();
                sdf = new SimpleDateFormat("yyyy-MM-dd");
                datelabel.setText(sdf.format(d));
                sdf = new SimpleDateFormat("HH:mm:ss");
                timelabel.setText(sdf.format(d));
            }
        });
        t.start();
    }

    private void AddtoCart() {
        try {
            barcodeno.grabFocus();
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);
            ResultSet rs = MyDB.search("select newbarcode,quantity,availableqty,date,time,sellingprice,unpack_pack_idpack,category_name from transfer");
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("newbarcode"));
                v.add(rs.getString("category_name"));
                v.add(rs.getString("quantity"));
                v.add(rs.getString("availableqty"));
                v.add(rs.getString("date"));
                v.add(rs.getString("time"));
                v.add(rs.getString("sellingprice"));
                v.add(rs.getString("unpack_pack_idpack"));
                dtm.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

