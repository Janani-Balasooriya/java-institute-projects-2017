    public boolean restoreDB(String dbUserName, String dbPassword, String source) {

        dbUserName = "root";
        dbPassword = "123";
        source = "H:/backup.sql";
        //source = "D:/backup.sql";
        String[] executeCmd = new String[]{"C:/Program Files (x86)/MySQL/MySQL Server 5.5/bin/mysql", "--user=" + dbUserName, "--password=" + dbPassword, "-e", "source " + source};

        Process runtimeProcess;
        try {

            runtimeProcess = Runtime.getRuntime().exec(executeCmd);
            int processComplete = runtimeProcess.waitFor();

            if (processComplete == 0) {
                System.out.println("Backup restored successfully");
                return true;
            } else {
                System.out.println("Could not restore the backup");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
        }

        return false;
    }

    public boolean backupDB(String dbName, String dbUserName, String dbPassword, String path) {
        dbName = "finalproject";
        dbUserName = "root";
        dbPassword = "123";
        path = "H:/backup.sql";

        String executeCmd = "C:/Program Files (x86)/MySQL/MySQL Server 5.5/bin/mysqldump -u " + dbUserName + " -p" + dbPassword + " --add-drop-database -B " + dbName + " -r " + path;
        Process runtimeProcess;
        try {

            runtimeProcess = Runtime.getRuntime().exec(executeCmd);
            int processComplete = runtimeProcess.waitFor();

            if (processComplete == 0) {
                System.out.println("Backup created successfully");
                return true;
            } else {
                System.out.println("Could not create the backup");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
        }

        return false;
    }
