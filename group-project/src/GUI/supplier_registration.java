    private void txt7KeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt7KeyTyped

        if (txt7.getText().length() < 9) {
            if (!Character.isDigit(evt.getKeyChar())) {
                evt.consume();
            }
        } else if (txt7.getText().length() < 10) {
            if (!Character.toString(evt.getKeyChar()).equalsIgnoreCase("V")) {
                evt.consume();

            } else {
                evt.setKeyChar(Character.toUpperCase(evt.getKeyChar()));
            }
        } else {
            evt.consume();
        }
        if (txt7.getText().length() < 9) {
            txt7.setBackground(Color.red);
        } else {
            txt7.setBackground(Color.white);
        }
    }//GEN-LAST:event_txt7KeyTyped

