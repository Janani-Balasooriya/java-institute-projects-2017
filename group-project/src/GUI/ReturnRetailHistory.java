    private void jComboBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jComboBox1ItemStateChanged
        if (jComboBox1.getSelectedItem().equals("Select")) {
            try {
                DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
                dtm.setRowCount(0);
                ResultSet rs = MyDB.search("select name,transfer_newbarcode,qty from invoiceitemi inner join invoiceitemreturni on"
                        + " idinvoiceitemi = invoiceitemi_idinvoiceitemi");

                if (rs.next()) {
                    Vector v = new Vector();
                    v.add(rs.getString("transfer_newbarcode"));
                    v.add(rs.getString("name"));
                    v.add(rs.getString("qty"));
                    dtm.addRow(v);
                }

            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jComboBox1ItemStateChanged

    private void searchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchKeyReleased
        try {
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);
            if (jComboBox1.getSelectedItem().equals("Barcode No")) {
                try {

                    ResultSet rs = MyDB.search("select name,transfer_newbarcode,qty from invoiceitemi inner join invoiceitemreturni on"
                            + " idinvoiceitemi = invoiceitemi_idinvoiceitemi where transfer_newbarcode = '" + search.getText() + "'");

                    if (rs.next()) {
                        Vector v = new Vector();
                        v.add(rs.getString("transfer_newbarcode"));
                        v.add(rs.getString("name"));
                        v.add(rs.getString("qty"));
                        dtm.addRow(v);
                    }
                    int qty = 0;
                    for (int i = 0; i < jTable1.getRowCount(); i++) {
                        qty += Integer.parseInt(jTable1.getValueAt(i, 2).toString());
                        String nam = jTable1.getValueAt(i, 1).toString();

                        caname.setText(nam);
                    }
                    recount.setText("" + qty);

                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
            if (jComboBox1.getSelectedItem().equals("Category Name")) {
                try {

                    ResultSet rs = MyDB.search("select name,transfer_newbarcode,qty from invoiceitemi inner join invoiceitemreturni on"
                            + " idinvoiceitemi = invoiceitemi_idinvoiceitemi where name like '%" + search.getText() + "%'");

                    if (rs.next()) {
                        Vector v = new Vector();
                        v.add(rs.getString("transfer_newbarcode"));
                        v.add(rs.getString("name"));
                        v.add(rs.getString("qty"));
                        dtm.addRow(v);
                    }
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }

            if (jComboBox1.getSelectedItem().equals("Quantity")) {

                try {

                    ResultSet rs = MyDB.search("select name,transfer_newbarcode,qty from invoiceitemi inner join invoiceitemreturni on"
                            + " idinvoiceitemi = invoiceitemi_idinvoiceitemi where qty = '" + search.getText() + "'");

                    if (rs.next()) {
                        Vector v = new Vector();
                        v.add(rs.getString("transfer_newbarcode"));
                        v.add(rs.getString("name"));
                        v.add(rs.getString("qty"));
                        dtm.addRow(v);
                    }
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_searchKeyReleased

