    public void Tableload() {
        try {
            ResultSet rs = MyDB.search("Select * from Cheque where status='pending'");
            DefaultTableModel tb = (DefaultTableModel) jTable1.getModel();
            tb.setRowCount(0);
            while (rs.next()) {
                Vector v = new Vector();

                v.add(rs.getString(2));
                v.add(rs.getString(3));
                v.add(rs.getString(4));
                v.add(rs.getString(5));
                v.add(rs.getString(6));
                v.add(rs.getString(7));
                v.add(rs.getString(8));
                v.add(rs.getString(9));
                v.add(rs.getString(10));
                tb.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void mouseclicke() {
        int i = jTable1.getSelectedRow();

        String chno = jTable1.getValueAt(i, 0).toString();
        String brno = jTable1.getValueAt(i, 1).toString();
        String Accno = jTable1.getValueAt(i, 2).toString();
        String chdate = jTable1.getValueAt(i, 3).toString();
        String chvlu = jTable1.getValueAt(i, 4).toString();
        String ownr = jTable1.getValueAt(i, 5).toString();
        String chtyp = jTable1.getValueAt(i, 6).toString();
        String stat = jTable1.getValueAt(i, 7).toString();
        if (stat.equals("Pending")) {

            Pendingradiobutton.setSelected(true);
           // JOptionPane.showMessageDialog(rootPane, "Pending");

        } else if (stat.equals("Accepted")) {

            AcceptedRadio.setSelected(true);
            JOptionPane.showMessageDialog(rootPane, "Accepted");
        } else {

            ReturnRadio.setSelected(true);
            JOptionPane.showMessageDialog(rootPane, "Return");
        }
        String invceno = jTable1.getValueAt(i, 8).toString();

        chequeNo.setText(chno);
        BranchNo.setText(brno);
        AccountNo.setText(Accno);
        ChequeDate.setText(chdate);
        ChequeValue.setText(chvlu);
        Owner.setText(ownr);
        ChequeType.setText(chtyp);
        InvoiceNo.setText(invceno);

    }

