    private void SetDateAndTime() {
        Timer t = new Timer(1000, new ActionListener() {

            @Override
            public void actionPerformed(ActionEvent e) {
                d = new Date();
                sdf = new SimpleDateFormat("yyyy-MM-dd");
                datelabel.setText(sdf.format(d));
                sdf = new SimpleDateFormat("HH:mm:ss");
                timelabel.setText(sdf.format(d));
            }
        });
        t.start();
    }

    private void AddtoCart() {
        try {
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);
            ResultSet rs = MyDB.search("select category_name,pack_idpack,originalqty,damageqty,qty,availableqty,unpack.unitprice,user_iduser from unpack"
                    + " inner join pack on unpack.pack_idpack = pack.idpack ");
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("pack_idpack"));
                v.add(rs.getString("category_name"));
                v.add(rs.getString("originalqty"));
                v.add(rs.getString("damageqty"));
                v.add(rs.getString("qty"));
                v.add(rs.getString("availableqty"));
                v.add(rs.getString("unitprice"));
                v.add(rs.getString("user_iduser"));
                dtm.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

