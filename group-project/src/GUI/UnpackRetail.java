    private void damageqtyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_damageqtyActionPerformed
        try {
            int ori = Integer.parseInt(originalqty.getText());
            int dam = Integer.parseInt(damageqty.getText());
            int bal = ori - dam;
            if (ori < dam) {
                JOptionPane.showMessageDialog(damageqty, "Exceed the items");
                damageqty.setText("");
                qty.setText("0");
                aqty.setText("0");
            } else {
                qty.setText("" + bal);
                aqty.setText("" + bal);
                int cost = d1 / bal;
                costprice.setText("" + cost);
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_damageqtyActionPerformed

