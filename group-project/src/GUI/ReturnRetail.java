    private void invoicenoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_invoicenoActionPerformed
        try {
            ResultSet rs1 = MyDB.search("select date from invoicei where invoicei = '" + invoiceno.getText() + "'");
            if (rs1.next()) {
                String da = rs1.getString("date");//invoice krpu dawasa.
                int invdate = calc.getArreasdaysCount(da);
                if (invdate < 7) {
                    invoicereturn.setEnabled(true);
                } else {
                    invoicereturn.setEnabled(false);
                }

            }
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            ResultSet rs = MyDB.search("select date,subtotal,discount,nettotal from invoicei where invoicei = '" + invoiceno.getText() + "'");

            if (rs.first()) {
                invoicedno.setText(rs.getString("date"));
                sublabel.setText(rs.getString("subtotal"));
                discount.setText(rs.getString("discount"));
                netlabel.setText(rs.getString("nettotal"));
                returndiscount.setText("0");
                AddCart();

            } else {
                invoicedno.setText("");
                sublabel.setText("");
                discount.setText("");
                netlabel.setText("");
                returndiscount.setText("0");
                dtm.setRowCount(0);

            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_invoicenoActionPerformed

