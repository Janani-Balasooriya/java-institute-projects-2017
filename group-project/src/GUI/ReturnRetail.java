    private void removeitembuttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeitembuttonActionPerformed
        try {
            int i = jTable2.getSelectedRow();
            DefaultTableModel dtm = (DefaultTableModel) jTable2.getModel();
            String val = dtm.getValueAt(i, 4).toString();
            double v = Double.parseDouble(val);
            double net = Double.parseDouble(returnnetlabel.getText());
            double amo = net - v;
            returnsublabel.setText("" + amo);
            returnnetlabel.setText("" + amo);
            qtylabel.setText("");
            dtm.removeRow(i);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Please select item to remove");
        }

    }//GEN-LAST:event_removeitembuttonActionPerformed

