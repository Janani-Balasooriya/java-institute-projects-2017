    private void jTree1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTree1MouseClicked
        try {
            if (jTree1.getSelectionPath().getPath().length == 2) {

                jComboBox1.setSelectedItem(jTree1.getSelectionPath().getPath()[1].toString());
                ResultSet rs = MyDB.search("select description from Category where name='" + jTree1.getSelectionPath().getPath()[1].toString() + "'");
                while (rs.next()) {
                    des.setText(rs.getString(1));
                }
            }
            loadCategory();
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jTree1MouseClicked

