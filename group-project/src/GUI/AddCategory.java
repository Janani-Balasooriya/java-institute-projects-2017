    private void loadJtree() {
        try {
            ResultSet rs = MyDB.search("SELECT name FROM Category");
            javax.swing.tree.DefaultMutableTreeNode treeNode1 = new javax.swing.tree.DefaultMutableTreeNode("Fashion Catagory");
            jTree1.setModel(new javax.swing.tree.DefaultTreeModel(treeNode1));
            while (rs.next()) {
                javax.swing.tree.DefaultMutableTreeNode treeNode3 = new javax.swing.tree.DefaultMutableTreeNode(rs.getString(1));
                treeNode1.add(treeNode3);
                jTree1.setModel(new javax.swing.tree.DefaultTreeModel(treeNode1));
                jScrollPane1.setViewportView(jTree1);

            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void loadCategory() {
        try {
            String n = jComboBox1.getEditor().getItem().toString();
            ResultSet r = MyDB.search("Select description from Category where '" + n + "'");
            while (r.next()) {
                des.setText(r.getString(1));
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
